/**
 * Vampire: the Masquerade 5e catalog entries (spec 037): English names and structure only.
 * Summaries, banes, compulsions, and predator grants live in
 * `translations/source/<locale>/data/v5-vampire-*.yaml` and load on demand (design D9).
 * Names are the books' (trait names may be used); sources: core rulebook, Players Guide,
 * Cults of the Blood Gods, and the free Russian lore supplement.
 */

export type VampireSource = 'core' | 'players-guide' | 'cults' | 'lore';

export interface VampireClanEntry {
    id: string;
    name: string;
    disciplines: readonly string[];
    source: VampireSource;
}

export interface VampireDisciplineEntry {
    id: string;
    name: string;
    source: VampireSource;
}

export interface VampirePowerEntry {
    id: string;
    name: string;
    discipline: string;
    level: number;
    /** Rouse checks to use the power (0 = free). */
    rouse: number;
    /** Another discipline the power needs, `<discipline>:<level>`. */
    amalgam?: string;
    source: VampireSource;
}

export interface VampireRitualEntry {
    id: string;
    name: string;
    discipline: string;
    level: number;
    kind: 'ritual' | 'ceremony' | 'formula';
    source: VampireSource;
}

export interface VampirePredatorTypeEntry {
    id: string;
    name: string;
    source: VampireSource;
}

